export const getPropertyById = (id) =>
  properties.find((p) => p.id === id)

export const getRelatedProperties = (property, count = 3) =>
  properties
    .filter(
      (p) =>
        p.id !== property.id &&
        (p.type === property.type || p.location === property.location)
    )
    .slice(0, count)

